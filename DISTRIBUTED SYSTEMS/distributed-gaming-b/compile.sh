#!/bin/bash
# ==============================================================
# compile.sh - Μεταγλώττιση όλων των Java αρχείων του project.
# ==============================================================
# Χρήση: ./compile.sh
# Εκτελέστε αυτό το script από τον ριζικό κατάλογο του project.
# ==============================================================

# Δημιουργία του φακέλου εξόδου (όπου θα γίνει build)
mkdir -p out

echo "Μεταγλώττιση όλων των Java αρχείων..."

# Βρίσκουμε όλα τα .java αρχεία αναδρομικά και τα μεταγλωττίζουμε
find src -name "*.java" | xargs javac -d out -sourcepath src

if [ $? -eq 0 ]; then
    echo "✓ Η μεταγλώττιση ολοκληρώθηκε επιτυχώς! Τα class αρχεία βρίσκονται στο φάκελο 'out/'."
else
    echo "✗ Η μεταγλώττιση απέτυχε. Ελέγξτε τα παραπάνω σφάλματα."
    exit 1
fi
